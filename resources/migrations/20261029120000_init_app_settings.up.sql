-- =============================================================
-- 应用设置表
-- =============================================================
-- 以 key/value 形式保存应用级配置（例如当前语言 language），
-- 对应 Go 模型 internal/db/models.AppSetting。
-- =============================================================

CREATE TABLE app_settings (
    -- =========================================================
    -- 主键
    -- =========================================================

    key         TEXT    NOT NULL PRIMARY KEY,
    -- 设置项键名，最长 100 字符，例如 language


    -- =========================================================
    -- 设置值
    -- =========================================================

    value       TEXT    NOT NULL,
    -- 设置项的值，统一按字符串保存
    -- 例如语言代码：zh-CN、en


    -- =========================================================
    -- 时间
    -- =========================================================

    updated_at  DATETIME DEFAULT CURRENT_TIMESTAMP
    -- 设置项最后更新时间，由 GORM 在写入时维护
);
